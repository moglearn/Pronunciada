class G2pEn:
    """Our numpy forward pass of the g2p_en checkpoint (GRU encoder-decoder, greedy decoding)."""
    GRAPH = ["<pad>", "<unk>", "</s>"] + list("abcdefghijklmnopqrstuvwxyz")
    PHON = ["<pad>", "<unk>", "<s>", "</s>"] + ["AA0", "AA1", "AA2", "AE0", "AE1", "AE2", "AH0", "AH1", "AH2", "AO0",
            "AO1", "AO2", "AW0", "AW1", "AW2", "AY0", "AY1", "AY2", "B", "CH", "D", "DH", "EH0", "EH1", "EH2", "ER0",
            "ER1", "ER2", "EY0", "EY1", "EY2", "F", "G", "HH", "IH0", "IH1", "IH2", "IY0", "IY1", "IY2", "JH", "K",
            "L", "M", "N", "NG", "OW0", "OW1", "OW2", "OY0", "OY1", "OY2", "P", "R", "S", "SH", "T", "TH", "UH0",
            "UH1", "UH2", "UW", "UW0", "UW1", "UW2", "V", "W", "Y", "Z", "ZH"]

    def __init__(self):
        import numpy as np

        self.np = np
        z = np.load(SRC / "g2pen" / "checkpoint20.npz", allow_pickle=False)
        self.v = {k: z[k] for k in z.files}

    def _cell(self, x, h, p):
        np = self.np
        v = self.v
        gi = x @ v[f"{p}_w_ih"].T + v[f"{p}_b_ih"]
        gh = h @ v[f"{p}_w_hh"].T + v[f"{p}_b_hh"]
        n3 = gi.shape[-1] // 3
        r = 1 / (1 + np.exp(-(gi[:, :n3] + gh[:, :n3])))
        zz = 1 / (1 + np.exp(-(gi[:, n3:2 * n3] + gh[:, n3:2 * n3])))
        n = np.tanh(gi[:, 2 * n3:] + r * gh[:, 2 * n3:])
        return (1 - zz) * n + zz * h

    def __call__(self, word: str) -> list[str]:
        np = self.np
        w = [c for c in word.lower() if c in self.GRAPH[3:]]
        if not w:
            return []
        ids = [self.GRAPH.index(c) for c in w] + [2]
        h = np.zeros((1, self.v["enc_w_hh"].shape[1]), np.float32)
        for i in ids:
            h = self._cell(self.v["enc_emb"][[i]], h, "enc")
        x = self.v["dec_emb"][[2]]
        out = []
        for _ in range(20):
            h = self._cell(x, h, "dec")
            k = int((h @ self.v["fc_w"].T + self.v["fc_b"]).argmax())
            if k == 3:
                break
            out.append(self.PHON[k])
            x = self.v["dec_emb"][[k]]
        return [p for p in out if not p.startswith("<")]


