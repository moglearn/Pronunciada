SUFFIXES = ("'s", "s'", "s", "es", "ies", "ed", "d", "ied", "ing", "ings", "ly", "ily", "er", "ers", "est", "iest",
            "ier", "ness", "less", "ful", "ment", "ments", "able", "ism", "isms", "ist", "ists", "ize", "ized", "izes",
            "izing", "ization", "ise", "ised", "ish", "ity", "ian", "ians", "al", "ally", "ic", "ical")
PREFIXES = ("un", "re", "pre", "non", "over", "under", "out", "mis", "dis", "anti", "co", "sub", "super", "inter",
            "semi", "multi", "mid", "counter", "post", "self")


def norm(t: str) -> str:
    t = unicodedata.normalize("NFC", t).lower().replace("’", "'")
    return re.sub(r"^\W+|\W+$", "", t)


def stems(w: str):
    """Candidate known stems of w by one suffix or one prefix (with e-restoration, undoubling, y/i)."""
    for suf in SUFFIXES:
        if w.endswith(suf) and len(w) - len(suf) >= 3:
            b = w[: -len(suf)]
            cands = [b, b + "e"]
            if suf in ("ies", "ied", "ily", "iest", "ier"):
                cands = [b + "y"]
            if len(b) >= 2 and b[-1] == b[-2] and b[-1] not in "aeiouls":
                cands.append(b[:-1])
            if b.endswith("i"):
                cands.append(b[:-1] + "y")
            for c in cands:
                yield ("suffix", suf, c)
    for pre in PREFIXES:
        if w.startswith(pre) and len(w) - len(pre) >= 3:
            yield ("prefix", pre, w[len(pre):].lstrip("-"))


def split_known(w: str, lex) -> list[str] | None:
    parts = [p for p in re.split(r"[-']", w) if p]
    if len(parts) >= 2 and all(p in lex for p in parts):
        return parts
    n = len(w)
    best = [None] * (n + 1)
    best[0] = []
    for i in range(n):
        if best[i] is None:
            continue
        for j in range(i + 4, n + 1):
            if w[i:j] in lex and (best[j] is None or len(best[i]) + 1 < len(best[j])):
                best[j] = best[i] + [w[i:j]]
    return best[n] if best[n] and len(best[n]) >= 2 else None


def classify(tok: str, w: str, lex, capital_mid: bool) -> str:
    letters = re.sub(r"[^a-zA-Z]", "", tok)
    if len(letters) >= 2 and letters.isupper() or (letters and not re.search(r"[aeiouyAEIOUY]", letters)):
        return "acronym"
    if re.search(r"[^\x00-\x7f]", w):
        return "foreign"
    if any(s in lex for _, _, s in stems(w)):
        return "morphology"
    if split_known(w, lex):
        return "compound"
    if capital_mid:
        return "name"
    return "other"


def guessed(g2p, w: str) -> bool:
    prons, oov, how = g2p._cache(w)
    return how == "rules"


