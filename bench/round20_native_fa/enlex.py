def _arpa_file(p: Path, comment="#") -> dict[str, list[list[str]]]:
    out = defaultdict(list)
    with open(p, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.split(comment)[0].strip() if comment else line.strip()
            if not line:
                continue
            parts = line.split()
            w = re.sub(r"\(\d+\)$", "", parts[0]).lower()
            ph = [x for x in parts[1:] if re.fullmatch(r"[A-Z]{1,2}[012]?", x)]
            if ph:
                out[w].append(ph)
    return dict(out)


@lru_cache(maxsize=None)
def source(name: str) -> dict[str, list[list[str]]]:
    if name == "cmu":
        return _arpa_file(SRC / "cmudict" / "cmudict.dict")
    if name == "ls":
        return _arpa_file(SRC / "librispeech" / "librispeech-lexicon.txt", comment=None)
    if name == "mfa_arpa":
        return _arpa_file(SRC / "mfa" / "english_us_arpa.dict", comment=None)
    if name == "mfa_ipa":
        out = defaultdict(list)
        for line in open(SRC / "mfa" / "english_us_mfa.dict", encoding="utf-8"):
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 2:
                out[parts[0].lower()].append(parts[-1].split())
        return dict(out)
    raise KeyError(name)


