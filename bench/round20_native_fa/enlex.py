def to_tokens(name: str, pron: list[str], word: str, g2p) -> list[str] | None:
    """A source pronunciation in the en front-end's notation (phone tokens with stress digits), rewritten."""
    from pronunciada.text._eu_build import arpa_to_ipa

    if name in ("cmu", "ls", "mfa_arpa", "g2pen"):
        try:
            toks = arpa_to_ipa(pron)
        except KeyError:
            return None
    else:
        toks = []
        for p in pron:
            if p in MFA_SYLLABIC:
                toks += MFA_SYLLABIC[p]
            elif p in MFA_MAP:
                toks.append(MFA_MAP[p])
            else:
                return None
        toks = g2p.fix_stress(toks, word)                   # MFA has no stress: the front-end's own rule
    return g2p.rewrite(toks, word)


def strip_stress(toks) -> tuple[str, ...]:
    from pronunciada.text import _eu_common as C

    return tuple(C.parse_phone(t)[0] for t in toks)


