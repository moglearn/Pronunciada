def derive(g2p, w):
    """Regular morphology and known-part compounds (stem / part readings from the shipped lexicon, lexicon
    notation; the caller applies the rewrite). None if no rule applies."""
    from pronunciada.text import _eu_common as C

    for kind, aff, stem in stems(w):
        base = lex_tokens(g2p, stem)
        if not base:
            continue
        if kind == "prefix":
            if aff in PRE_PH:
                return PRE_PH[aff] + base
            continue
        ph = SUF_PH.get(aff, "skip")
        last = C.parse_phone(base[-1])[0]
        if ph == "skip":
            continue
        if ph is None:                                    # plural / possessive / 3rd person
            if aff == "ies" and last == "i":
                return base + ["z"]
            return base + (["ɪ", "z"] if last in SIBILANT else ["s"] if last in VOICELESS else ["z"])
        if ph == "ED":
            if aff == "ied":
                return base + ["d"]
            return base + (["ɪ", "d"] if last in ("t", "d") else ["t"] if last in VOICELESS | {"s", "ʃ", "tʃ"} else ["d"])
        if aff in ("ily", "ier", "iest") and last == "i":
            base = base[:-1]
        if aff == "ly" and last in ("l", "l̴"):            # -al + -ly: one l
            return base + ["i"]
        return base + list(ph)
    parts = split_known(w, g2p.lex)
    if parts:
        out = []
        for j, p in enumerate(parts):
            for t in lex_tokens(g2p, p):
                ipa, st = C.parse_phone(t)
                out.append(ipa + ("" if st is None else str(1 if (st == 1 and j == 0) else (2 if st else 0))))
        return out
    return None


def oracle_tokens(g2p, w, method, _ref=[]):  # noqa: B006
    """Lexicon-notation tokens for a guessed word under an oracle method, or None (keep the letter table)."""
    if method == "morph":
        return derive(g2p, w)
    if method == "ls":
        from pronunciada.text._eu_build import arpa_to_ipa

        d = source("ls")
        try:
            return arpa_to_ipa(d[w][0]) if w in d else None
        except KeyError:
            return None
    if method == "g2pen":
        if not _ref:
            _ref.append(G2pEn())
        from pronunciada.text._eu_build import arpa_to_ipa

        p = _ref[0](w)
        try:
            return arpa_to_ipa(p) if p else None
        except KeyError:
            return None
    if method == "best":
        return oracle_tokens(g2p, w, "morph") or oracle_tokens(g2p, w, "ls")
    raise KeyError(method)


def oracle_reference(g2p, text, method):
    """The prompt's Reference with every guessed (letter-rule) single-item word replaced by the oracle reading."""
    from pronunciada.r20 import _token_fragment, replace_word

    ref = g2p(text)
    for wi, wd in enumerate(ref.words):
        w = norm(wd.text)
        if not w or not re.fullmatch(r"[a-z'-]+", w) or not guessed(g2p, w):
            continue
        toks = oracle_tokens(g2p, w, method)
        if not toks:
            continue
        frag = _token_fragment(g2p, wd.text, g2p.rewrite(toks, w))
        ref = replace_word(ref, wi, frag)
    return ref


METHODS = ("morph", "ls", "g2pen", "best")


def guessed_items(lang="en"):
    from pronunciada.text import get_g2p

    g2p = get_g2p(lang)
    out = []
    for it in K.practice_items(lang):
        ref = g2p(it["target"])
        if any(norm(w.text) and re.fullmatch(r"[a-z'-]+", norm(w.text)) and guessed(g2p, norm(w.text)) for w in ref.words):
            out.append(it["id"])
    return out


