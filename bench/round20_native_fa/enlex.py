def edit(a, b):
    n, m = len(a), len(b)
    d = list(range(m + 1))
    for i in range(1, n + 1):
        prev, d[0] = d[0], i
        for j in range(1, m + 1):
            cur = d[j]
            d[j] = min(d[j] + 1, d[j - 1] + 1, prev + (a[i - 1] != b[j - 1]))
            prev = cur
    return d[m]


def cmd_sources():
    from pronunciada.text import get_g2p

    g2p = get_g2p("en")
    lex = g2p.lex
    pack = set(lex)
    types = json.loads((OUT / "enlex_types.json").read_text())
    rows = K.word_rows("en", None, fix_labels=True, measure=True)
    thr = K.threshold(rows)
    tok_w, fa_w = Counter(), Counter()
    for r in rows:
        if not r["label"]:
            w = norm(r["tok"])
            if w in types:
                tok_w[w] += 1
                fa_w[w] += r["err"] >= thr
    ref = G2pEn()
    srcs = {n: source(n) for n in ("cmu", "ls", "mfa_arpa", "mfa_ipa")}
    res = {"sizes": {n: len(d) for n, d in srcs.items()}, "packaged_cmudict_words": len(pack)}
    res["cmu_latest_new_vs_packaged"] = len(set(srcs["cmu"]) - pack)
    res["cmu_packaged_missing_from_latest"] = len(pack - set(srcs["cmu"]))
    # (a) coverage of guessed practice words
    cov = {}
    for n, d in list(srcs.items()) + [("ls_hand", {w: v for w, v in srcs["ls"].items() if w in srcs["cmu"]})]:
        cov[n] = {"types": sum(1 for w in types if w in d) / max(1, len(types)),
                  "tokens": sum(c for w, c in tok_w.items() if w in d) / max(1, sum(tok_w.values())),
                  "fa": sum(c for w, c in fa_w.items() if w in d) / max(1, sum(fa_w.values())),
                  "by_class_tokens": {c: sum(cnt for w, cnt in tok_w.items() if types[w] == c and w in d)
                                      / max(1, sum(cnt for w, cnt in tok_w.items() if types[w] == c)) for c in CLASSES}}
    res["coverage_of_guessed"] = cov
    # (b) letter-table error on words a source has and the packaged CMUdict lacks; and g2p_en on the same words
    per = {}
    for n in ("ls", "mfa_arpa", "mfa_ipa"):
        d = srcs[n]
        words = sorted(w for w in d if w not in pack and re.fullmatch(r"[a-z']+", w))[:20000]
        e_lts = e_ref = tot = 0
        by = defaultdict(lambda: [0, 0, 0])
        for w in words:
            t = to_tokens(n, d[w][0], w, g2p)
            if not t:
                continue
            gold = strip_stress(t)
            lts = strip_stress(g2p.rewrite(g2p.fix_stress([p for p in g2p.oov(w) if p], w), w))
            nn = to_tokens("g2pen", ref(w), w, g2p)
            r2 = strip_stress(nn) if nn else ()
            a, b = edit(lts, gold), edit(r2, gold)
            e_lts += a
            e_ref += b
            tot += len(gold)
            cls = classify(w, w, lex, False)
            by[cls][0] += a
            by[cls][1] += b
            by[cls][2] += len(gold)
        per[n] = {"words": len(words), "per_letter_table": e_lts / max(1, tot), "per_g2p_en": e_ref / max(1, tot),
                  "by_class": {c: {"per_letter_table": v[0] / max(1, v[2]), "per_g2p_en": v[1] / max(1, v[2])}
                               for c, v in by.items()}}
        print(n, {k: (round(v, 4) if isinstance(v, float) else v) for k, v in per[n].items() if k != "by_class"}, flush=True)
    res["letter_table_error"] = per
    # (c) agreement with CMUdict (packaged) on shared words, stress ignored: first reading equal / any reading equal
    agree = {}
    for n in ("ls", "mfa_arpa", "mfa_ipa"):
        d = srcs[n]
        shared = sorted(w for w in d if w in pack)[:30000]
        first = anyr = 0
        for w in shared:
            ours = [strip_stress(g2p.rewrite(list(p), w)) for p in [x for x in __import__(
                "pronunciada.text._eu_common", fromlist=["split_prons"]).split_prons(lex[w])]]
            t = to_tokens(n, d[w][0], w, g2p)
            if not t:
                continue
            s = strip_stress(t)
            first += s == ours[0]
            anyr += s in ours
        agree[n] = {"shared_checked": len(shared), "first_reading_equal": first / max(1, len(shared)),
                    "any_reading_equal": anyr / max(1, len(shared))}
        print(n, agree[n], flush=True)
    res["agreement_with_cmudict"] = agree
    K.save_json("enlex_sources.json", res)
    print(json.dumps({k: v for k, v in res.items() if k in ("sizes", "cmu_latest_new_vs_packaged",
                                                            "cmu_packaged_missing_from_latest")}))
    for n, v in cov.items():
        print("coverage", n, {k: round(x, 3) for k, x in v.items() if k != "by_class_tokens"},
              {c: round(x, 2) for c, x in v["by_class_tokens"].items()})


